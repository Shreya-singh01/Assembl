"""Demo data for local development - SYNTHETIC, clearly labelled.

    python -m app.seed            # seeds the database in MONGODB_URL
    SEED_DEMO=1 (with MONGODB_URL=memory://) seeds the in-memory DB at startup

Every demo account uses an ``@demo.assembl.example`` address, its display name
ends with "(demo)", and every demo profile and project is generated by
app.research.synthetic. Refuses to run when ENVIRONMENT=production.
"""

from __future__ import annotations

import asyncio
import random

from app.core.config import get_settings
from app.core.security import hash_password
from app.db.mongo import create_client, ensure_indexes, is_memory_client
from app.research.synthetic import ARCHETYPES, _student
from app.services.auth import now
from app.services.messaging import sync_team_conversation

DEMO_DOMAIN = "demo.assembl.example"  # RFC 2606 reserved; passes e-mail validation
DEMO_PASSWORD = "demo-password-123"
FIRST = ["Aarav", "Diya", "Kabir", "Meera", "Rohan", "Sana", "Ishaan", "Tara", "Vivaan", "Anaya", "Arjun", "Zoya",
         "Neel", "Riya", "Dev", "Kiara", "Yash", "Ira", "Kunal", "Nisha", "Om", "Pari", "Reyansh", "Siya"]


async def seed(db, n_students: int = 24, seed_value: int = 7) -> dict:
    if get_settings().environment == "production":
        raise RuntimeError("refusing to seed demo data in production")
    if await db.users.find_one({"email": {"$regex": f"@{DEMO_DOMAIN}$"}}):
        return {"skipped": "demo data already present"}
    rng = random.Random(seed_value)
    arche = list(ARCHETYPES)
    pw = hash_password(DEMO_PASSWORD)
    ids = []
    for i in range(n_students):
        name = FIRST[i % len(FIRST)]
        handle = f"{name.lower()}_demo{i}"
        res = await db.users.insert_one({
            "email": f"{handle}@{DEMO_DOMAIN}", "password_hash": pw, "display_name": f"{name} (demo)", "handle": handle,
            "handle_key": handle, "role": "student", "created_at": now(),
            "consent": {"terms_accepted_at": now(), "research_participation": False}, "demo": True,
        })
        uid = res.inserted_id
        ids.append(uid)
        p = _student(rng, str(uid), arche[i % len(arche)])
        await db.profiles.insert_one({
            "_id": uid, "year": p["year"], "branch": p["branch"],
            "skills": [{"label": s, "proficiency": v, "kind": "technical", "recognized": True, "original": s}
                       for s, v in sorted(p["skills"].items())],
            "declared_absent": [], "primary_roles": p["primary_roles"], "secondary_roles": p["secondary_roles"],
            "interests": p["interests"],
            "projects": [{"title": t, "summary": "", "contribution": "", "link": None} for t in p["project_summaries"]],
            "links": [], "availability": p["availability"], "weekly_hours": p["weekly_hours"], "work_mode": p["work_mode"],
            "visible": True, "updated_at": now(), "demo": True,
        })
    # One demo team that is already recruiting.
    owner, member = ids[0], ids[2]
    project = {
        "title": "Placement-prep platform (demo)",
        "description": "Demo project: a web application that helps students prepare for campus placements with mock tests, "
                       "interview practice and progress analytics.",
        "opportunity_type": "hackathon", "event_key": None,
        "requirements": [
            {"skill": "React", "importance": 2, "desired_proficiency": 3, "mandatory": False},
            {"skill": "Node.js", "importance": 3, "desired_proficiency": 3, "mandatory": False},
            {"skill": "PostgreSQL", "importance": 3, "desired_proficiency": 2, "mandatory": False},
            {"skill": "Machine Learning", "importance": 2, "desired_proficiency": 2, "mandatory": False},
            {"skill": "UI Design", "importance": 1, "desired_proficiency": 2, "mandatory": False},
        ],
        "target_size": 4, "vacant_roles": ["Backend", "Designer"], "allowed_years": None, "role_mandatory": False,
        "synchronous": False, "min_shared_slots": 0, "availability_policy": "all", "availability_mandatory": False,
        "weekly_hours": 10, "work_mode": "hybrid", "unverifiable_policy": "exclude", "visibility": "public",
        "owner_id": owner,
        "members": [{"user_id": owner, "role": "Frontend", "joined_at": now()}, {"user_id": member, "role": "ML", "joined_at": now()}],
        "open_positions": 2, "status": "open",
        "history": [{"at": now(), "type": "created", "user_id": owner, "by": owner}],
        "created_at": now(), "updated_at": now(), "version": 0, "demo": True,
    }
    res = await db.projects.insert_one(project)
    project["_id"] = res.inserted_id
    await sync_team_conversation(db, project)
    return {"students": len(ids), "demo_login": f"{(await db.users.find_one({'_id': owner}))['email']} / {DEMO_PASSWORD}"}


async def _main() -> None:
    s = get_settings()
    client = create_client(s.mongodb_url)
    db = client[s.mongodb_db]
    await ensure_indexes(db, memory=is_memory_client(client))
    print(await seed(db))
    client.close()


if __name__ == "__main__":
    asyncio.run(_main())
